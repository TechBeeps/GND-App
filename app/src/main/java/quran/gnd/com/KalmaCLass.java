package quran.gnd.com;
public class KalmaCLass {
    private String name,kalma,meaning;
    public KalmaCLass(){}
    public KalmaCLass(String name, String kalma, String meaning){this.name = name;this.kalma = kalma;this.meaning = meaning;}
    public String getName() {return name;}
    public void setName(String name) {this.name = name;}
    public String getKalma() {return kalma;}
    public void setKalma(String kalma) {this.kalma = kalma;}
    public String getMeaning() {return meaning;}
    public void setMeaning(String meaning) {this.meaning = meaning;}
}
